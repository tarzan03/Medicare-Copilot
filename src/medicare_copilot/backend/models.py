class Patient(Base):
    __tablename__ = "patients"

    patient_id = Column(String(20), primary_key=True, index=True)
    patient_name = Column(String(150), nullable=False)
    age = Column(Integer, nullable=True)
    gender = Column(String(30), nullable=True)

    email = Column(String(255), nullable=True, unique=True)
    phone_number = Column(String(25), nullable=True)

    diagnosis = Column(Text, nullable=True)
    current_medication = Column(Text, nullable=True)

    lab_test = Column(String(150), nullable=True)
    lab_value = Column(Float, nullable=True)
    lab_unit = Column(String(50), nullable=True)

    last_visit_date = Column(Date, nullable=True)
    next_scheduled_visit = Column(Date, nullable=True)
    days_since_last_visit = Column(Integer, nullable=True)
    missed_last_appointment = Column(Boolean, nullable=True)

    vitals_bp_systolic = Column(Integer, nullable=True)
    vitals_bp_diastolic = Column(Integer, nullable=True)
    vitals_heart_rate = Column(Integer, nullable=True)
    vitals_spo2 = Column(Float, nullable=True)

    notes = Column(Text, nullable=True)


