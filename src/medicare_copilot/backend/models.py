class RAGChunk(Base):
    __tablename__ = "rag_table"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)

    document_id = Column(UUID(as_uuid=True), nullable=False, index=True)
    document_name = Column(String(512), nullable=False)

    chunk_index = Column(Integer, nullable=False)
    content = Column(Text, nullable=False)

    start_page = Column(Integer, nullable=False)
    end_page = Column(Integer, nullable=False)

    chunk_metadata = Column(
        "metadata",
        JSONB,
        nullable=False,
        default=dict,
    )

    embedding = Column(Vector(1024), nullable=False)

    # Generated by PostgreSQL from the canonical chunk text.
    search_vector = Column(
        TSVECTOR,
        Computed(
            "to_tsvector('english'::regconfig, content)",
            persisted=True,
        ),
        nullable=False,
    )

    created_at = Column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )

    __table_args__ = (
        Index(
            "ix_rag_table_search_vector",
            "search_vector",
            postgresql_using="gin",
        ),
        Index(
            "ix_rag_table_document_chunk",
            "document_id",
            "chunk_index",
            unique=True,
        ),
        Index(
            "ix_rag_chunks_embedding_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_ops={"embedding": "vector_cosine_ops"},
            postgresql_with={
                "m": 16,
                "ef_construction": 64,
            },
        ),
    )
